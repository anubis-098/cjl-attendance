test("editing own email keeps the current login and its original expiry", async ({ page, request }) => {
  const before = await (await request.get("/api/auth/me")).json();
  await page.goto("/accounts");
  const row = page.getByRole("row").filter({ has: page.getByRole("cell", { name: "testadmin", exact: true }) });
  await row.getByRole("button", { name: "แก้ไข", exact: true }).click();
  await page.getByLabel("Email (ไม่บังคับ)").fill("admin@example.com");
  await page.getByRole("button", { name: "บันทึก", exact: true }).click();
  await expect(row.getByRole("cell", { name: "admin@example.com", exact: true })).toBeVisible();
  await page.reload();
  await expect(page).toHaveURL(/\/accounts$/);
  const response = await request.get("/api/auth/me");
  expect(response.ok()).toBeTruthy();
  expect((await response.json()).expiresAt).toBe(before.expiresAt);
  const me = (await (await request.get("/api/accounts")).json()).accounts.find((a: { username: string }) => a.username === "testadmin");
  const changed = await request.put("/api/accounts", { data: { ...me, password: "replacement-password" } });
  expect(changed.ok()).toBeTruthy();
  expect((await changed.json()).requiresLogin).toBe(true);
  expect((await request.get("/api/auth/me")).status()).toBe(401);
});
