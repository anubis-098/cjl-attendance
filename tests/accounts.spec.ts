test("login protection, Supervisor permissions, 24-hour expiration and logout revocation", async ({ playwright, request, page }) => {
  const anon = await playwright.request.newContext({ baseURL: "http://localhost:3001" });
  for (const url of ["/api/workspace", "/api/source-data?type=employees", "/api/payroll?month=2026-09", "/api/accounts", "/api/attendance-evidence?employeeId=A&date=2026-09-03", "/api/attendance-evidence/00000000-0000-0000-0000-000000000000"])
    expect((await anon.get(url)).status()).toBe(401);
  for (const url of ["/api/import", "/api/holidays", "/api/shifts", "/api/attendance-evidence"])
    expect((await anon.post(url, { data: {} })).status()).toBe(401);
  for (const url of ["/api/workspace", "/api/payroll", "/api/calendar-remarks", "/api/company-holidays"])
    expect((await anon.put(url, { data: {} })).status()).toBe(401);
  expect((await anon.post("/api/auth/login", { data: { username: "testsupervisor", password: "wrong" } })).status()).toBe(401);
  const login = await anon.post("/api/auth/login", { data: { username: "testsupervisor", password: TEST_PASSWORD } });
  expect(login.ok()).toBeTruthy();
  const cookie = (await anon.storageState()).cookies.find(c => c.name === "cj_session")!;
  expect(cookie.httpOnly).toBe(true); expect(cookie.sameSite).toBe("Strict");
  const claims = JSON.parse(Buffer.from(cookie.value.split(".")[1], "base64url").toString());
  expect(claims.exp - claims.iat).toBe(86400);
  expect((await anon.get("/api/workspace")).ok()).toBeTruthy();
  expect((await anon.get("/api/payroll?month=2026-09&cycle=26-25")).ok()).toBeTruthy();
  for (const method of ["get", "post", "put", "delete"] as const)
    expect((await anon[method]("/api/accounts", { data: {} })).status()).toBe(403);
  expect((await anon.put("/api/calendar-remarks", { headers: { Origin: "https://evil.example" }, data: {} })).status()).toBe(403);
  const expired = signToken(claims.sub, claims.jti, TEST_SECRET, Math.floor(Date.now()/1000)-86400).token;
  const expiredResponse = await request.get("/api/workspace", { headers: { Cookie: `cj_session=${expired}` } });
  expect(expiredResponse.status()).toBe(401);
  expect((await anon.post("/api/auth/logout")).ok()).toBeTruthy();
  expect((await request.get("/api/workspace", { headers: { Cookie: `cj_session=${cookie.value}` } })).status()).toBe(401);
  await page.context().clearCookies();
  await page.goto("/attendance"); await expect(page).toHaveURL(/\/login/);
  await page.getByLabel("ชื่อผู้ใช้").fill("testsupervisor");
  await page.getByLabel("รหัสผ่าน", { exact: true }).fill(TEST_PASSWORD);
  await page.getByRole("button", { name: "เข้าสู่ระบบ", exact: true }).click();
  await expect(page).toHaveURL(/\/attendance/);
  await expect(page.getByRole("link", { name: "จัดการบัญชี", exact: true })).toHaveCount(0);
  await page.goto("/accounts"); await expect(page).toHaveURL(/\/attendance/);
  await anon.dispose();
});
test("Super Admin creates, edits, disables and deletes accounts; existing sessions are revoked", async ({ page, request, playwright }) => {
  await page.goto("/accounts");
  await page.getByRole("button", { name: "สร้างบัญชี", exact: true }).click();
  await page.getByLabel("ชื่อผู้ใช้", { exact: true }).fill("newperson");
  await page.getByLabel("ชื่อแสดง", { exact: true }).fill("New Supervisor");
  await page.getByLabel("รหัสผ่าน", { exact: true }).fill(TEST_PASSWORD);
  await page.getByRole("button", { name: "บันทึก", exact: true }).click();
  await expect(page.getByRole("cell", { name: "newperson", exact: true })).toBeVisible();
  const other = await playwright.request.newContext({ baseURL: "http://localhost:3001" });
  expect((await other.post("/api/auth/login", { data: { username: "newperson", password: TEST_PASSWORD } })).ok()).toBeTruthy();
  let rows = (await (await request.get("/api/accounts")).json()).accounts;
  let row = rows.find((r: { username: string }) => r.username === "newperson");
  expect((await request.put("/api/accounts", { data: { ...row, displayName: "Renamed", active: false, password: "" } })).ok()).toBeTruthy();
  expect((await other.get("/api/workspace")).status()).toBe(401);
  expect((await other.post("/api/auth/login", { data: { username: "newperson", password: TEST_PASSWORD } })).status()).toBe(401);
  expect((await request.put("/api/accounts", { data: { ...row, password: "" } })).status()).toBe(400);
  rows = (await (await request.get("/api/accounts")).json()).accounts;
  row = rows.find((r: { username: string }) => r.username === "newperson");
  expect((await request.delete("/api/accounts", { data: { id: row.id, version: row.version } })).ok()).toBeTruthy();
  const me = rows.find((r: { username: string }) => r.username === "testadmin");
  expect((await request.delete("/api/accounts", { data: { id: me.id, version: me.version } })).status()).toBe(400);
  expect((await request.put("/api/accounts", { data: { ...me, active: false, password: "" } })).status()).toBe(400);
  await other.dispose();
});
test("password change revokes previous sessions and requires the new password", async ({ request, playwright }) => {
  const user = await playwright.request.newContext({ baseURL: "http://localhost:3001" });
  await user.post("/api/auth/login", { data: { username: "testsupervisor", password: TEST_PASSWORD } });
  expect((await user.post("/api/auth/password", { data: { currentPassword: "wrong", password: "Replacement-password-2026" } })).status()).toBe(400);
  expect((await user.post("/api/auth/password", { data: { currentPassword: TEST_PASSWORD, password: "Replacement-password-2026" } })).ok()).toBeTruthy();
  expect((await user.get("/api/workspace")).status()).toBe(401);
  expect((await user.post("/api/auth/login", { data: { username: "testsupervisor", password: TEST_PASSWORD } })).status()).toBe(401);
  expect((await user.post("/api/auth/login", { data: { username: "testsupervisor", password: "Replacement-password-2026" } })).ok()).toBeTruthy();
  await user.dispose();
});
