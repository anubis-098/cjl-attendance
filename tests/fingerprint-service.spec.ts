test("service tokens, append, idempotency, invalid file, revocation and permissions",async({request,page})=> {
  expect((await request.post("/api/fingerprint-service/upload",{data:"X 20260930 0800"})).status()).toBe(401);
  const create=await request.post("/api/fingerprint-service/manage",{data:{name:"Test Client"}});
  expect(create.status()).toBe(201); const {id,token}=await create.json();
  const auth={Authorization:`Bearer ${token}`,"X-Machine-Name":"TEST-CLIENT"};
  expect((await request.post("/api/fingerprint-service/heartbeat",{headers:auth})).ok()).toBeTruthy();
  const key=randomUUID();
  const upload=(body:string,requestId=key)=>request.post("/api/fingerprint-service/upload",{headers:{...auth,"X-Request-ID":requestId,"X-Filename":"test.txt","Content-Type":"text/plain"},data:body});
  const raw="TEST-UPLOAD 20260929 2000\nTEST-UPLOAD 20260930 0500\nTEST-UPLOAD 20260930 0500";
  const first=await upload(raw); expect(first.ok()).toBeTruthy();
  expect((await first.json()).summary).toMatchObject({added:2,duplicates:1});
  const repeat=await upload(raw); expect(repeat.ok()).toBeTruthy(); expect((await repeat.json()).summary.added).toBe(2);
  const duplicate=await upload(raw,randomUUID()); expect((await duplicate.json()).summary).toMatchObject({added:0,duplicates:3,total:2});
  const concurrent=await Promise.all(Array.from({length:6},()=>upload(raw,randomUUID())));
  for(const response of concurrent) { expect(response.ok()).toBeTruthy(); expect((await response.json()).summary.added).toBe(0); }
  expect((await upload("TEST-UPLOAD 20260930 0600")).status()).toBe(409);
  expect((await upload("TEST-UPLOAD 20260931 0800",randomUUID())).status()).toBe(400);
  const status=await (await request.get("/api/fingerprint-service/manage")).json();
  expect(status.services.find((s:{id:string})=>s.id===id)).toMatchObject({connected:true,machine_name:"TEST-CLIENT"});
  expect(JSON.stringify(status)).not.toContain(token);
  await page.goto("/fingerprints");
  await expect(page.getByRole("heading",{name:/Client file transfer|รับข้อมูลจากเครื่อง Client/})).toBeVisible();
  await request.post("/api/auth/login",{data:{username:"testsupervisor",password:TEST_PASSWORD}});
  expect((await request.post("/api/fingerprint-service/manage",{data:{name:"Denied"}})).status()).toBe(403);
  expect((await request.delete(`/api/fingerprint-service/manage?id=${id}`)).status()).toBe(403);
  await request.post("/api/auth/login",{data:{username:"testadmin",password:TEST_PASSWORD}});
  expect((await request.delete(`/api/fingerprint-service/manage?id=${id}`)).ok()).toBeTruthy();
  expect((await request.post("/api/fingerprint-service/heartbeat",{headers:auth})).status()).toBe(401);
  expect((await upload(raw,randomUUID())).status()).toBe(401);
});

test("Windows client retains failed upload and delivers its pending TXT to the real test API",async({request})=> {
  test.setTimeout(90000);
  const exe=path.resolve("Finger_Service/publish-client/CJFingerService.exe");
  await access(exe);
  const created=await (await request.post("/api/fingerprint-service/manage",{data:{name:"Windows upload test"}})).json();
  const root=path.resolve("Finger_Service/test-data/upload-"+randomUUID());
  const runId=randomUUID(),directory=path.join(root,"pending",runId);
  await mkdir(directory,{recursive:true});
  const raw="CLIENT-TEST 20260929 2000\nCLIENT-TEST 20260930 0500\n";
  await writeFile(path.join(directory,"client.txt"),raw);
  await writeFile(path.join(directory,"manifest.json"),JSON.stringify({runId,filename:"client.txt",sha256:createHash("sha256").update(raw).digest("hex")}));
  const env={...process.env,CJ_FINGER_SERVICE_DATA:root};
  const configure=(token:string)=>execFileSync("powershell.exe",["-NoProfile","-NonInteractive","-Command",`Add-Type -AssemblyName System.Security; $value=[Console]::In.ReadToEnd(); $secret=[Convert]::ToBase64String([Security.Cryptography.ProtectedData]::Protect([Text.Encoding]::UTF8.GetBytes($value),$null,[Security.Cryptography.DataProtectionScope]::CurrentUser)); @{ServerUrl='http://localhost:3001';EnableUpload=$true;TokenProtected=$secret} | ConvertTo-Json | Set-Content -LiteralPath (Join-Path $env:CJ_FINGER_SERVICE_DATA 'settings.json') -Encoding UTF8`],{input:token,env,windowsHide:true});
  const run=()=>promisify(execFile)(exe,["--upload-only"],{env,windowsHide:true,timeout:60000});
  configure("x".repeat(43)); await run();
  expect(JSON.parse(await readFile(path.join(root,"worker-result.json"),"utf8")).ok).toBe(false);
  expect(await readFile(path.join(directory,"client.txt"),"utf8")).toBe(raw);
  await expect(access(path.join(directory,"uploaded.json"))).rejects.toThrow();
  configure(created.token); await run();
  const result=JSON.parse(await readFile(path.join(root,"worker-result.json"),"utf8"));
  expect(result.ok).toBe(true);
  const receipt=JSON.parse(await readFile(path.join(directory,"uploaded.json"),"utf8"));
  expect(receipt.response.summary).toMatchObject({added:2,duplicates:0});
  await run();
  expect(JSON.parse(await readFile(path.join(root,"worker-result.json"),"utf8")).message).toContain("Uploaded 0");
  await request.delete(`/api/fingerprint-service/manage?id=${created.id}`);
});
